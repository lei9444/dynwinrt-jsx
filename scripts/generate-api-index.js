'use strict'

const fs = require('node:fs')
const path = require('node:path')
const ts = require('typescript')

const repoRoot = path.resolve(__dirname, '..')
const outputPath = path.join(
  repoRoot,
  'docs',
  'api-index.md',
)
const entries = [
  ['dynwinrt-jsx', 'src/index.ts'],
  ['dynwinrt-jsx/host', 'src/host.ts'],
  ['dynwinrt-jsx/worker', 'src/worker.ts'],
]

function compact(value, maximum = 220) {
  const normalized = value.replace(/\s+/g, ' ').trim()
  return normalized.length <= maximum
    ? normalized
    : `${normalized.slice(0, maximum - 1)}…`
}

function symbolKind(symbol) {
  const declarations = symbol.declarations ?? []
  if (declarations.some(ts.isClassDeclaration)) return 'class'
  if (declarations.some(ts.isInterfaceDeclaration)) return 'interface'
  if (declarations.some(ts.isTypeAliasDeclaration)) return 'type'
  if (declarations.some(ts.isEnumDeclaration)) return 'enum'
  if (declarations.some(ts.isFunctionDeclaration)) return 'function'
  return 'value'
}

function signatureFor(checker, symbol, location, kind) {
  const type = kind === 'interface' || kind === 'type'
    ? checker.getDeclaredTypeOfSymbol(symbol)
    : checker.getTypeOfSymbolAtLocation(symbol, location)
  const calls = checker.getSignaturesOfType(
    type,
    ts.SignatureKind.Call,
  )
  if (calls.length > 0) {
    return compact(
      calls
        .map((signature) =>
          checker.signatureToString(
            signature,
            location,
            ts.TypeFormatFlags.NoTruncation,
          ),
        )
        .join(' | '),
    )
  }
  return compact(
    checker.typeToString(
      type,
      location,
      ts.TypeFormatFlags.NoTruncation,
    ),
  )
}

function sourceFor(symbol) {
  const declaration = symbol.declarations?.[0]
  if (!declaration) return ''
  const relative = path.relative(
    repoRoot,
    declaration.getSourceFile().fileName,
  )
  const line =
    declaration
      .getSourceFile()
      .getLineAndCharacterOfPosition(
        declaration.getStart(),
      ).line + 1
  return `${relative.replaceAll('\\', '/')}:${line}`
}

const configPath = ts.findConfigFile(
  repoRoot,
  ts.sys.fileExists,
  'tsconfig.json',
)
if (!configPath) {
  throw new Error('tsconfig.json was not found.')
}
const config = ts.readConfigFile(
  configPath,
  ts.sys.readFile,
)
const parsed = ts.parseJsonConfigFileContent(
  config.config,
  ts.sys,
  repoRoot,
)
const entryPaths = entries.map(([, file]) =>
  path.join(repoRoot, file),
)
const program = ts.createProgram({
  rootNames: [
    ...new Set([
      ...parsed.fileNames,
      ...entryPaths,
    ]),
  ],
  options: parsed.options,
})
const checker = program.getTypeChecker()
const sections = []

for (const [entryName, file] of entries) {
  const source = program.getSourceFile(
    path.join(repoRoot, file),
  )
  if (!source) {
    throw new Error(`Missing entry source: ${file}`)
  }
  const moduleSymbol = checker.getSymbolAtLocation(source)
  if (!moduleSymbol) {
    throw new Error(`Missing module symbol: ${file}`)
  }
  const rows = checker
    .getExportsOfModule(moduleSymbol)
    .filter((symbol) => !symbol.name.startsWith('__'))
    .map((exported) => {
      const symbol =
        exported.flags & ts.SymbolFlags.Alias
          ? checker.getAliasedSymbol(exported)
          : exported
      const kind = symbolKind(symbol)
      return {
        name: exported.name,
        kind,
        signature: signatureFor(
          checker,
          symbol,
          source,
          kind,
        ),
        source: sourceFor(symbol),
      }
    })
    .sort((left, right) =>
      left.name.localeCompare(right.name),
    )
  sections.push({
    entryName,
    file,
    rows,
  })
}

const lines = [
  '# Public API index',
  '',
  '<!-- Generated by scripts/generate-api-index.js. -->',
  '',
  'Compact signatures for the supported package entry points. Run `npm run docs:api` after changing public exports.',
  '',
]
for (const section of sections) {
  lines.push(
    `## \`${section.entryName}\``,
    '',
    `Source: \`${section.file}\``,
    '',
    '| Symbol | Kind | Signature | Defined at |',
    '|---|---|---|---|',
  )
  for (const row of section.rows) {
    lines.push(
      `| \`${row.name}\` | ${row.kind} | \`${row.signature.replaceAll('|', '\\|')}\` | \`${row.source}\` |`,
    )
  }
  lines.push('')
}
const output = lines.join('\n')

if (process.argv.includes('--check')) {
  const current = fs.existsSync(outputPath)
    ? fs.readFileSync(outputPath, 'utf8')
    : ''
  if (current !== output) {
    console.error(
      'docs/api-index.md is stale. Run npm run docs:api.',
    )
    process.exitCode = 1
  }
}
else {
  fs.writeFileSync(outputPath, output)
  console.log(
    `Generated ${path.relative(repoRoot, outputPath)}.`,
  )
}
